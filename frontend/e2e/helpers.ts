import process from "node:process";
import {
  expect,
  type Browser,
  type Page,
  type Locator,
} from "@playwright/test";

type Role = "cutting" | "verifier" | "sewing";

const routes: Record<Role, string> = {
  cutting: "/cutting/orders",
  verifier: "/verification",
  sewing: "/sewing",
};

// -----------------------------------------
// LOGIN
// -----------------------------------------

export async function loginAs(browser: Browser, role: Role): Promise<Page> {
  const email = process.env[`E2E_${role.toUpperCase()}_EMAIL`];
  const password = process.env[`E2E_${role.toUpperCase()}_PASSWORD`];

  if (!email || !password) {
    throw new Error(`Missing Playwright credentials for ${role}`);
  }

  const page = await browser.newPage();

  await page.goto("/login");

  await page.getByLabel("Work email").fill(email);
  await page.locator('input[name="password"]').fill(password);

  await page
    .getByRole("button", {
      name: "Sign in to workspace",
    })
    .click();

  await expect(page).toHaveURL(new RegExp(`${routes[role]}$`), {
    timeout: 15000,
  });

  return page;
}

// -----------------------------------------
// FIND ORDER
// -----------------------------------------

export async function findOrder(
  page: Page,
  orderNumber: string,
): Promise<Locator> {
  const search = page.getByRole("textbox", {
    name: "Search orders",
  });

  await search.fill(orderNumber);

  const row = page.getByRole("row").filter({
    hasText: orderNumber,
  });

  await expect(row).toBeVisible({
    timeout: 15000,
  });

  return row;
}

// -----------------------------------------
// CREATE AND SUBMIT CUTTING ORDER
// -----------------------------------------

export async function createAndSubmitOrder(
  page: Page,
  rollId: string,
): Promise<string> {
  await page
    .getByRole("button", {
      name: "Create Order",
    })
    .click();

  const dialog = page.getByRole("dialog", {
    name: "Create Cutting Order",
  });

  await expect(dialog).toBeVisible();

  // Native select options are not always visually visible.
  await dialog
    .getByRole("option", {
      name: "Casual Blouse (REC-BL01)",
    })
    .waitFor({ state: "attached" });

  await dialog.getByLabel("Production Recipe").selectOption({
    label: "Casual Blouse (REC-BL01)",
  });

  await expect(dialog.getByText("Expected Production")).toBeVisible();

  await dialog.getByLabel("Target Quantity").fill("3");

  await dialog.getByLabel("Actual Fabric Used (yards)").fill("5.4");

  await dialog.getByLabel("Fabric Roll ID").fill(rollId);

  // Capture the actual order generated by the backend.
  const createResponsePromise = page.waitForResponse(
    (response) =>
      response.request().method() === "POST" &&
      /\/cutting-orders\/?$/.test(new URL(response.url()).pathname),
  );

  await dialog
    .getByRole("button", {
      name: "Create Order",
    })
    .click();

  const createResponse = await createResponsePromise;

  expect(
    createResponse.status(),
    "Cutting order creation must return HTTP 201",
  ).toBe(201);

  const createdOrder: {
    order_no?: string;
    fabric_roll_id?: string;
  } = await createResponse.json();

  const orderNumber = createdOrder.order_no;

  if (!orderNumber) {
    throw new Error("The create-order API did not return an order_no");
  }

  expect(createdOrder.fabric_roll_id).toBe(rollId);

  await expect(dialog).toBeHidden();

  // Search by generated order number, not fabric-roll ID.
  const row = await findOrder(page, orderNumber);

  await row
    .getByRole("button", {
      name: "View",
    })
    .click();

  const orderDialog = page.getByRole("dialog", {
    name: `Order ${orderNumber}`,
  });

  await expect(orderDialog).toBeVisible();

  await expect(orderDialog.getByText(rollId)).toBeVisible();

  await orderDialog
    .getByRole("button", {
      name: "Submit for Verification",
    })
    .click();

  const confirmation = page.getByRole("dialog", {
    name: "Submit cutting order?",
  });

  await expect(confirmation).toBeVisible();

  await confirmation
    .getByRole("button", {
      name: "Submit Order",
    })
    .click();

  await expect(confirmation).toBeHidden();
  await expect(orderDialog).toBeHidden();

  return orderNumber;
}

// -----------------------------------------
// OPEN VERIFICATION
// -----------------------------------------

export async function openVerification(
  page: Page,
  orderNumber: string,
): Promise<Locator> {
  const row = await findOrder(page, orderNumber);

  await row
    .getByRole("button", {
      name: "Verify Batch",
    })
    .click();

  const dialog = page.getByRole("dialog", {
    name: `Verify ${orderNumber}`,
  });

  await expect(dialog).toBeVisible();

  await expect(dialog.locator('input[id^="count-"]').first()).toBeVisible();

  return dialog;
}

// -----------------------------------------
// RECORD COMPONENT COUNTS
// -----------------------------------------

export async function recordCounts(
  page: Page,
  shortage: boolean,
): Promise<void> {
  const dialog = page.getByRole("dialog").filter({
    has: page.locator('input[id^="count-"]'),
  });

  const inputs = dialog.locator('input[id^="count-"]');

  await expect(inputs.first()).toBeVisible();

  const total = await inputs.count();

  expect(total).toBeGreaterThan(0);

  for (let index = 0; index < total; index++) {
    const input = inputs.nth(index);

    const card = input.locator(
      'xpath=ancestor::div[contains(@class,"rounded-2xl")][1]',
    );

    const content = await card.innerText();

    const match = content.match(/Expected:\s*(\d+)\s*pieces/);

    if (!match) {
      throw new Error(
        `Cannot find expected quantity for component ${index + 1}`,
      );
    }

    const expectedQty = Number(match[1]);

    const actualQty = shortage && index === 0 ? expectedQty - 1 : expectedQty;

    if (actualQty < 0) {
      throw new Error("Cannot create a shortage for a zero-quantity component");
    }

    await input.fill(String(actualQty));

    const saveButton = card.getByRole("button", {
      name: "Save Count",
    });

    await expect(saveButton).toBeEnabled();

    const responsePromise = page.waitForResponse(
      (response) =>
        response.request().method() === "PATCH" &&
        /\/verification\/orders\/[^/]+\/items\/[^/]+/.test(
          new URL(response.url()).pathname,
        ),
    );

    await saveButton.click();

    const response = await responsePromise;

    expect(
      response.ok(),
      `Saving component ${index + 1} must succeed`,
    ).toBeTruthy();

    await expect(saveButton).toBeDisabled();
  }
}

// -----------------------------------------
// APPROVE VERIFIED ORDER
// -----------------------------------------

export async function approveOrder(
  page: Page,
  orderNumber: string,
): Promise<void> {
  const dialog = page.getByRole("dialog", {
    name: `Verify ${orderNumber}`,
  });

  const approveButton = dialog.getByRole("button", {
    name: "Approve",
    exact: true,
  });

  await expect(approveButton).toBeEnabled();

  await approveButton.click();

  const confirmation = page.getByRole("dialog", {
    name: "Approve batch?",
  });

  await expect(confirmation).toBeVisible();

  await confirmation
    .getByRole("button", {
      name: "Approve",
      exact: true,
    })
    .click();

  await expect(confirmation).toBeHidden();
  await expect(dialog).toBeHidden();
}
